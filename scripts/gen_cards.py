"""Regenerate src/data/cards.ts and copy the card art from the game project.

    python -I scripts/gen_cards.py [path/to/BreedhavenCard]

The card ids to show are listed in SHOWCASE, in gallery order.
"""
import json
import re
import shutil
import sys
from pathlib import Path

SHOWCASE = "051 102 087 040 147 193 212 188 052 138 090 056 185 054 173 149".split()
# The hero fan also uses SOR_051, SOR_087 and SOR_102 (src/components/Hero.astro).

SITE = Path(__file__).resolve().parent.parent
GAME = Path(sys.argv[1] if len(sys.argv) > 1 else SITE.parent / "BreedhavenCard") / "game"

FACTION = {"Vigilance": "verdant", "Command": "iron", "Aggression": "unbound",
           "Cunning": "somnial", "Heroism": "astral", "Villainy": "gilded"}

cards = {c["id"]: c for c in json.loads((GAME / "data/sets/sor.json").read_text("utf-8"))["cards"]}
rules = json.loads((GAME / "data/lexicon.json").read_text("utf-8"))["rules"]


def lexicon(text):
    for pattern, replacement in rules:
        text = re.sub(pattern, replacement, text)
    return text


out = ['''import type { ImageMetadata } from "astro";
import type { FactionId } from "./factions";

// Generated by scripts/gen_cards.py from BreedhavenCard/game/data/sets/sor.json,
// with the game's lexicon (game/data/lexicon.json) applied to the rules text, so
// every name, stat and line here is what the card says in the game.
''']
for n in SHOWCASE:
    out.append(f'import art{n} from "../assets/cards/sor-{n}.webp";')
    shutil.copyfile(GAME / f"assets/art/cards/SOR_{n}.webp", SITE / f"src/assets/cards/sor-{n}.webp")

out.append('''
export interface ShowcaseCard {
  id: string;
  name: string;
  subtitle?: string;
  type: "Unit" | "Event" | "Upgrade";
  /** The world a unit fights in. */
  world?: "Waking" | "Dreaming";
  factions: FactionId[];
  cost: number;
  power?: number;
  hp?: number;
  traits: string[];
  text: string;
  rarity: "rare" | "legendary";
  art: ImageMetadata;
}

/** The cards the gallery shows, in order. */
export const showcase: ShowcaseCard[] = [''')

for n in SHOWCASE:
    c = cards[f"SOR_{n}"]
    factions = list(dict.fromkeys(FACTION[a] for a in c["aspects"]))
    o = {"id": c["id"], "name": c["name"]}
    if c.get("subtitle"):
        o["subtitle"] = c["subtitle"]
    o["type"] = c["type"].capitalize()
    if c["type"] == "unit":
        o["world"] = "Waking" if c["arena"] == "ground" else "Dreaming"
    o["factions"] = factions
    o["cost"] = c["cost"]
    if c["type"] in ("unit", "upgrade"):
        o["power"], o["hp"] = c["power"], c["hp"]
    o["traits"] = [lexicon(t) for t in c["traits"]]
    o["text"] = lexicon(c.get("text") or "")
    o["rarity"] = c["rarity"]
    fields = "".join(f"    {k}: {json.dumps(v, ensure_ascii=False)},\n" for k, v in o.items())
    out.append(f"  {{\n{fields}    art: art{n},\n  }},")

out.append("];\n")
(SITE / "src/data/cards.ts").write_text("\n".join(out), "utf-8")
print(f"wrote {len(SHOWCASE)} cards")
